// Rule-based conjugation of SOUND Form I verbs (three strong root letters). The rules are fixed and
// regular for this class, so tables are computed, not typed. Weak, doubled and hamzated verbs are excluded.
import { shuffle, pick, sample } from './arabic';
import type { Q } from './gen';

const A = 'َ', U = 'ُ', I = 'ِ', S = 'ْ', SH = 'ّ';
const V: Record<string, string> = { a: A, u: U, i: I };
export type Verb = { r: [string, string, string]; past: 'a' | 'i' | 'u'; pres: 'a' | 'i' | 'u'; en: string; ing: string };
export const VERBS: Verb[] = [
  { r: ['ك', 'ت', 'ب'], past: 'a', pres: 'u', en: 'wrote', ing: 'write' }, { r: ['ن', 'ص', 'ر'], past: 'a', pres: 'u', en: 'helped', ing: 'help' },
  { r: ['ع', 'ل', 'م'], past: 'i', pres: 'a', en: 'knew', ing: 'know' }, { r: ['خ', 'ل', 'ق'], past: 'a', pres: 'u', en: 'created', ing: 'create' },
  { r: ['ذ', 'ك', 'ر'], past: 'a', pres: 'u', en: 'remembered', ing: 'remember' }, { r: ['س', 'م', 'ع'], past: 'i', pres: 'a', en: 'heard', ing: 'hear' },
  { r: ['ض', 'ر', 'ب'], past: 'a', pres: 'i', en: 'struck', ing: 'strike' }, { r: ['ف', 'ت', 'ح'], past: 'a', pres: 'a', en: 'opened', ing: 'open' },
  { r: ['ج', 'ع', 'ل'], past: 'a', pres: 'a', en: 'made', ing: 'make' }, { r: ['ع', 'م', 'ل'], past: 'i', pres: 'a', en: 'did', ing: 'do' },
  { r: ['ك', 'ف', 'ر'], past: 'a', pres: 'u', en: 'disbelieved', ing: 'disbelieve' }, { r: ['ظ', 'ل', 'م'], past: 'a', pres: 'i', en: 'wronged', ing: 'wrong' },
  { r: ['د', 'خ', 'ل'], past: 'a', pres: 'u', en: 'entered', ing: 'enter' }, { r: ['خ', 'ر', 'ج'], past: 'a', pres: 'u', en: 'went out', ing: 'go out' },
  { r: ['ر', 'ج', 'ع'], past: 'a', pres: 'i', en: 'returned', ing: 'return' }, { r: ['غ', 'ف', 'ر'], past: 'a', pres: 'i', en: 'forgave', ing: 'forgive' },
  { r: ['ش', 'ك', 'ر'], past: 'a', pres: 'u', en: 'gave thanks', ing: 'give thanks' }, { r: ['ص', 'ب', 'ر'], past: 'a', pres: 'i', en: 'was patient', ing: 'be patient' },
];
export const PERSONS = [
  ['3ms', 'هُوَ', 'he'], ['3md', 'هُمَا', 'they two (m.)'], ['3mp', 'هُمْ', 'they (m.)'], ['3fs', 'هِيَ', 'she'], ['3fd', 'هُمَا', 'they two (f.)'], ['3fp', 'هُنَّ', 'they (f.)'],
  ['2ms', 'أَنْتَ', 'you (m. sg.)'], ['2md', 'أَنْتُمَا', 'you two'], ['2mp', 'أَنْتُمْ', 'you (m. pl.)'], ['2fs', 'أَنْتِ', 'you (f. sg.)'], ['2fp', 'أَنْتُنَّ', 'you (f. pl.)'],
  ['1s', 'أَنَا', 'I'], ['1p', 'نَحْنُ', 'we'],
] as const;
const PERF: Record<string, [string, string]> = { // [vowel on r3, ending]
  '3ms': [A, ''], '3md': [A, 'ا'], '3mp': [U, 'وا'], '3fs': [A, 'تْ'], '3fd': [A, 'تَا'], '3fp': [S, 'نَ'], '2ms': [S, 'تَ'], '2md': [S, 'تُمَا'], '2mp': [S, 'تُمْ'], '2fs': [S, 'تِ'], '2fp': [S, 'تُنَّ'], '1s': [S, 'تُ'], '1p': [S, 'نَا'],
};
const IMPF: Record<string, [string, string, string]> = { // [prefix, vowel on r3, ending]
  '3ms': ['ي', U, ''], '3md': ['ي', A, 'انِ'], '3mp': ['ي', U, 'ونَ'], '3fs': ['ت', U, ''], '3fd': ['ت', A, 'انِ'], '3fp': ['ي', S, 'نَ'], '2ms': ['ت', U, ''], '2md': ['ت', A, 'انِ'], '2mp': ['ت', U, 'ونَ'], '2fs': ['ت', I, 'ينَ'], '2fp': ['ت', S, 'نَ'], '1s': ['أ', U, ''], '1p': ['ن', U, ''],
};
const IMPV: Record<string, [string, string]> = { '2ms': [S, ''], '2md': [A, 'ا'], '2mp': [U, 'وا'], '2fs': [I, 'ي'], '2fp': [S, 'نَ'] };
export function conj(v: Verb, tense: 'perf' | 'impf' | 'impv', p: string): string | undefined {
  const [a, b, c] = v.r;
  if (tense === 'perf') { const e = PERF[p]; return a + A + b + V[v.past] + c + e[0] + e[1]; }
  if (tense === 'impf') { const e = IMPF[p]; return e[0] + A + a + S + b + V[v.pres] + c + e[1] + e[2]; }
  const e = IMPV[p]; if (!e) return;
  return 'ا' + (v.pres === 'u' ? U : I) + a + S + b + V[v.pres] + c + e[0] + e[1];
}
export const dict = (v: Verb) => `${conj(v, 'perf', '3ms')} / ${conj(v, 'impf', '3ms')}`;
let n = 0;
export function conjQ(tense: 'perf' | 'impf' | 'impv'): Q {
  const v = pick(VERBS);
  const ps = PERSONS.filter((p) => conj(v, tense, p[0]));
  const p = pick(ps as any) as (typeof PERSONS)[number];
  const right = conj(v, tense, p[0])!;
  const others = [...new Set(sample(ps as any, 12).map((x: any) => conj(v, tense, x[0])!))].filter((x) => x !== right).slice(0, 3);
  const options = shuffle([right, ...others]);
  const what = tense === 'perf' ? `${p[2]} ${v.en}` : tense === 'impf' ? `${p[2]} ${v.ing}${/^(he|she)$/.test(p[2]) ? 's' : ''}` : `${v.ing}! (to ${p[2]})`;
  return { id: `c${n++}`, kind: 'mcq', tag: `sarf.conj.${tense}`, prompt: `Build the verb: “${what}”`, ar: `${p[1]} · ${dict(v)}`, options, optAr: true, answer: options.indexOf(right), explain: `${p[1]} + ${conj(v, 'perf', '3ms')} → ${right}. Generated by the regular rule for sound Form I verbs.`, verified: true };
}
